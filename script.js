  function resolver(indice, motivo) {
    if (!jogo || jogo.bloqueado || jogo.finalizado) return;
  
    jogo.bloqueado = true;
  
    const pergunta = jogo.perguntas[jogo.indice];
    const acertou =
      motivo === "resposta" && pergunta.opcoes[indice]?.correta;
  
    const pulou = motivo === "pular";
    const correta = pergunta.opcoes.find(opcao => opcao.correta).texto;
  
    if (acertou) {
      jogo.acertos++;
      jogo.sequencia++;
      jogo.melhorSequencia = Math.max(jogo.melhorSequencia, jogo.sequencia);
    } else {
      jogo.sequencia = 0;
  
      if (!pulou && jogo.modo !== "treino") {
        jogo.vidas--;
      }
    }
  
    jogo.premio = Math.round(
      premioMaximo * Math.pow(jogo.acertos / jogo.perguntas.length, 2)
    );
  
    jogo.historico.push({
      pergunta: pergunta.pergunta,
      correta,
      escolhida: indice === null ? null : pergunta.opcoes[indice].texto,
      motivo,
      acertou: Boolean(acertou),
      explicacao: pergunta.explicacao || ""
    });
  
    [...$("alternativas").children].forEach((botao, indice) => {
      botao.disabled = true;
  
      if (pergunta.opcoes[indice].correta) {
        botao.classList.add("correta");
      } else if (motivo === "resposta") {
        botao.classList.add("errada");
      }
    });
  
    const prefixo = acertou
      ? "✓ Mandou bem!"
      : pulou
        ? "↗ Passou o microfone, sem pontuar."
        : motivo === "tempo"
          ? "⌛ O beat parou: tempo esgotado."
          : "✕ Errou a rima.";
  
    $("feedback").textContent =
      `${prefixo} Resposta: ${correta}. ${pergunta.explicacao || ""}`;
  
    atualizarPainel();
    atualizarAjudas();
  
    $("proxima").textContent =
      jogo.indice + 1 >= jogo.perguntas.length ||
      (jogo.modo !== "treino" && jogo.vidas <= 0)
        ? "VER RESULTADO →"
        : "PRÓXIMA RODADA →";
  
    $("proxima").hidden = false;
  }
  
